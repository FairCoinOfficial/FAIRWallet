/**
 * Config plugin: withFairWalletReleaseSigning
 *
 * Every FAIRWallet Android release is signed with FAIRWallet's own release key
 * (alias `fairwallet`, certificate SHA-256 `RELEASE_CERT_SHA256` below), never
 * with Expo's debug keystore: Google Play refuses a debug-signed upload, and a
 * "release" signed with the public debug key could be built by anyone. Android
 * only installs an update signed by the same certificate as the installed app,
 * so this certificate is what makes a FAIRWallet APK FAIRWallet's.
 *
 * It edits `android/app/build.gradle` in three places:
 *
 * 1. Before `android {`: resolve the keystore from Gradle properties (set in
 *    `~/.gradle/gradle.properties`, with `-P`, or as `ORG_GRADLE_PROJECT_<name>`
 *    environment variables; never in the repository):
 *      - `FAIRWALLET_UPLOAD_STORE_FILE`: the keystore (`~/` is expanded).
 *      - `FAIRWALLET_UPLOAD_STORE_PASSWORD`, or `FAIRWALLET_UPLOAD_STORE_PASSWORD_FILE`:
 *        a file holding it (trimmed).
 *      - `FAIRWALLET_UPLOAD_KEY_ALIAS`: `fairwallet`.
 *      - `FAIRWALLET_UPLOAD_KEY_PASSWORD` / `FAIRWALLET_UPLOAD_KEY_PASSWORD_FILE`:
 *        optional, defaults to the store password (a PKCS12 keystore has one).
 * 2. `signingConfigs.release` from those, and the `release` buildType signed by
 *    it. Expo's template signs release with the debug key; nothing here falls
 *    back to it. The `debug` buildType keeps Expo's debug key.
 * 3. `fairwalletVerifyReleaseSigning`, a task every release variant's
 *    `pre…ReleaseBuild` and `validateSigning…Release` depend on (so
 *    `assembleRelease` and `bundleRelease` alike). It opens the release
 *    buildType's EFFECTIVE signing config and fails the build unless the key's
 *    certificate SHA-256 is FAIRWallet's, so a missing keystore, the debug key,
 *    another key and a wrong alias all fail the build. Debug builds never run it.
 *
 * There is deliberately no opt-out: a FAIRWallet release signed with anything
 * else must not exist. A build that needs no key is a debug build.
 *
 * `android/` is generated by `expo prebuild`, so these edits live here or they
 * are lost on the next prebuild.
 */
const { withAppBuildGradle } = require('expo/config-plugins');

/** SHA-256 of FAIRWallet's release certificate (alias `fairwallet`), lowercase hex. */
const RELEASE_CERT_SHA256 = 'b4c80ff0be972aefa219f4e435ce267eae3650e19ff5df209374d3775d9e207f';

const MARKER = '@generated fairwallet-release-signing';
const PLUGIN = '[withFairWalletReleaseSigning]';

/** Gradle property names holding the release signing material. */
const PROPERTIES = {
  storeFile: 'FAIRWALLET_UPLOAD_STORE_FILE',
  storePassword: 'FAIRWALLET_UPLOAD_STORE_PASSWORD',
  keyAlias: 'FAIRWALLET_UPLOAD_KEY_ALIAS',
  keyPassword: 'FAIRWALLET_UPLOAD_KEY_PASSWORD',
};

/** Resolves the FAIRWALLET_UPLOAD_* properties; inserted before `android {`. */
const RESOLVE_PROPERTIES = `// ${MARKER}: FAIRWallet's release key
// (plugins/withFairWalletReleaseSigning.js). Edit the plugin, never this file.
def fairwalletHomePath = { String path -> path.startsWith('~/') ? System.getProperty('user.home') + path.substring(1) : path }
def fairwalletSigningProblems = []
def fairwalletSigningSecret = { String name ->
    def value = findProperty(name)
    if (value != null) return value.toString()
    def path = findProperty(name + '_FILE')
    if (path == null) return null
    def secretFile = file(fairwalletHomePath(path.toString()))
    if (!secretFile.isFile()) {
        fairwalletSigningProblems << (name + '_FILE names ' + secretFile + ', which is not a file')
        return null
    }
    return secretFile.getText('UTF-8').trim()
}
def fairwalletStoreFilePath = findProperty('${PROPERTIES.storeFile}')
def fairwalletStoreFile = fairwalletStoreFilePath == null ? null : file(fairwalletHomePath(fairwalletStoreFilePath.toString()))
def fairwalletStorePassword = fairwalletSigningSecret('${PROPERTIES.storePassword}')
def fairwalletKeyAlias = findProperty('${PROPERTIES.keyAlias}')?.toString()
def fairwalletKeyPassword = fairwalletSigningSecret('${PROPERTIES.keyPassword}') ?: fairwalletStorePassword
if (fairwalletStoreFile == null) fairwalletSigningProblems << '${PROPERTIES.storeFile} is not set'
if (fairwalletStorePassword == null && findProperty('${PROPERTIES.storePassword}_FILE') == null) fairwalletSigningProblems << '${PROPERTIES.storePassword} (or ${PROPERTIES.storePassword}_FILE) is not set'
if (fairwalletKeyAlias == null) fairwalletSigningProblems << '${PROPERTIES.keyAlias} is not set'
def fairwalletUploadSigning = fairwalletStoreFile != null && fairwalletStorePassword != null && fairwalletKeyAlias != null

`;

const RELEASE_SIGNING_CONFIG = `        release {
            // ${MARKER}: FAIRWallet's key from the FAIRWALLET_UPLOAD_* properties.
            // Without them it stays empty and fairwalletVerifyReleaseSigning fails the build.
            if (fairwalletUploadSigning) {
                storeFile fairwalletStoreFile
                storePassword fairwalletStorePassword
                keyAlias fairwalletKeyAlias
                keyPassword fairwalletKeyPassword
            }
        }
`;

const RELEASE_SIGNING_LINE = 'signingConfig signingConfigs.release';

/** The fail-closed guard; appended to the file. */
const VERIFY_TASK = String.raw`
// ${MARKER}: every release build must carry FAIRWallet's certificate. This
// checks the release buildType's EFFECTIVE signing config, however it was set.
def fairwalletVerifyReleaseSigning = tasks.register('fairwalletVerifyReleaseSigning') {
    group = 'verification'
    description = "Fails unless the release build is signed with FAIRWallet's release certificate."
    notCompatibleWithConfigurationCache('reads the android extension when it runs')
    doLast {
        def expected = '${RELEASE_CERT_SHA256}'
        def fail = { String reason ->
            throw new GradleException([
                'FAIRWallet release signing: ' + reason,
                '',
                "Every FAIRWallet Android release is signed with FAIRWallet's release key (certificate SHA-256 " + expected + ').',
                'Provide it as Gradle properties, in ~/.gradle/gradle.properties, as -P<name>=<value>,',
                'or as ORG_GRADLE_PROJECT_<name> environment variables:',
                '  ${PROPERTIES.storeFile}=<path to the keystore>',
                '  ${PROPERTIES.storePassword}_FILE=<file holding its password> (or ${PROPERTIES.storePassword})',
                '  ${PROPERTIES.keyAlias}=fairwallet',
                '  ${PROPERTIES.keyPassword}[_FILE] only when the key password differs from the store password',
                'A build without the key is a debug build (assembleDebug).',
            ].join('\n'))
        }
        def config = android.buildTypes.getByName('release').signingConfig
        if (config == null || config.storeFile == null) {
            fail('the release build has no keystore' + (fairwalletSigningProblems ? ': ' + fairwalletSigningProblems.join('; ') : '') + '.')
        }
        def keyStore = null
        try {
            keyStore = java.security.KeyStore.getInstance(config.storeFile, config.storePassword?.toCharArray())
        } catch (Exception e) {
            fail('could not open ' + config.storeFile + ' (' + e.getClass().getSimpleName() + ': ' + e.getMessage() + ').')
        }
        def certificate = keyStore.getCertificate(config.keyAlias)
        if (certificate == null) {
            fail(config.storeFile.toString() + ' has no certificate under the alias "' + config.keyAlias + '".')
        }
        def actual = java.security.MessageDigest.getInstance('SHA-256').digest(certificate.getEncoded()).encodeHex().toString()
        if (actual != expected) {
            fail('the release build is signed by "' + config.name + '" (' + config.storeFile + ', alias ' + config.keyAlias + '), certificate SHA-256 ' + actual + ", not FAIRWallet's.")
        }
    }
}
tasks.configureEach { task ->
    if (task.name ==~ /pre\w*ReleaseBuild|validateSigning\w*Release/) {
        task.dependsOn(fairwalletVerifyReleaseSigning)
    }
}
`;

function fail(message) {
  throw new Error(`${PLUGIN} ${message}`);
}

/**
 * Apply the edits to the text of a Groovy `android/app/build.gradle`.
 * Idempotent; refuses a file that already has a release signing config.
 *
 * @param {string} contents
 * @returns {string}
 */
function applyReleaseSigning(contents) {
  if (contents.includes(MARKER)) return contents;

  const androidBlock = /^android \{$/m;
  if (!androidBlock.test(contents)) {
    fail(
      'Could not find the top-level `android {` block in app/build.gradle. The Expo template changed: update this plugin.',
    );
  }
  let next = contents.replace(androidBlock, `${RESOLVE_PROPERTIES}android {`);

  // Declare signingConfigs.release immediately after the generated debug entry.
  const debugSigningBlock =
    /(signingConfigs\s*\{\s*\n\s*debug\s*\{[\s\S]*?\n\s{8}\}\n)(\s*release\s*\{)?/;
  const debugMatch = next.match(debugSigningBlock);
  if (!debugMatch) {
    fail(
      'Could not find the generated signingConfigs.debug block in app/build.gradle. The Expo template changed: update this plugin.',
    );
  }
  if (debugMatch[2]) {
    fail(
      'app/build.gradle already declares signingConfigs.release. Remove whatever writes it: this plugin is the one source of the release signing config.',
    );
  }
  next = next.replace(debugSigningBlock, `$1${RELEASE_SIGNING_CONFIG}`);

  // Point the release buildType at it. The debug buildType has its own
  // `signingConfig signingConfigs.debug`, so only the line inside `release {` is replaced.
  const buildTypes = next.indexOf('buildTypes {');
  const releaseBuildType = buildTypes === -1 ? -1 : next.indexOf('release {', buildTypes);
  if (releaseBuildType === -1) {
    fail('Could not find the release buildType in app/build.gradle.');
  }
  const releaseBody = next.slice(releaseBuildType);
  const signingLine = releaseBody.match(/signingConfig [^\n]+/);
  const closing = releaseBody.indexOf('\n        }');
  if (
    !signingLine ||
    signingLine.index === undefined ||
    (closing !== -1 && signingLine.index > closing)
  ) {
    fail('Could not find the signingConfig line of the release buildType in app/build.gradle.');
  }
  const at = releaseBuildType + signingLine.index;
  next = next.slice(0, at) + RELEASE_SIGNING_LINE + next.slice(at + signingLine[0].length);

  return `${next.replace(/\n*$/, '\n')}${VERIFY_TASK}`;
}

/** @param {import('expo/config').ExpoConfig} config */
function withFairWalletReleaseSigning(config) {
  return withAppBuildGradle(config, (modConfig) => {
    if (modConfig.modResults.language !== 'groovy') {
      fail(`Expected a Groovy app/build.gradle, got ${modConfig.modResults.language}.`);
    }
    modConfig.modResults.contents = applyReleaseSigning(modConfig.modResults.contents);
    return modConfig;
  });
}

module.exports = withFairWalletReleaseSigning;
module.exports.applyReleaseSigning = applyReleaseSigning;
module.exports.RELEASE_CERT_SHA256 = RELEASE_CERT_SHA256;
module.exports.PROPERTIES = PROPERTIES;
